-- 11. payments : การชำระเงิน / แจ้งโอน
-- ---------------------------------------------------------------------
create table public.payments (
  payment_id       int generated by default as identity primary key,
  invoice_id       int not null references public.invoices (invoice_id) on delete restrict,
  payment_date     date not null default current_date,
  amount           decimal(10,2) not null check (amount > 0),
  payment_method   varchar(30) not null
                   check (payment_method in ('cash', 'transfer', 'promptpay')),
  slip_image       varchar(255),
  transaction_ref  varchar(100),
  status           varchar(30) not null default 'pending'
                   check (status in ('pending', 'verified', 'rejected')),
  note             text,
  verified_by      uuid references public.users (user_id) on delete set null,
  verified_at      timestamptz,
  created_at       timestamptz not null default now(),

  -- รอตรวจสอบ ⇔ ยังไม่มีเวลาตรวจสอบ
  constraint payments_verified_consistency
    check ((status = 'pending') = (verified_at is null))
);

create index payments_invoice_idx on public.payments (invoice_id);
create index payments_status_idx  on public.payments (status);

