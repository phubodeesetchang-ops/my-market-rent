-- 10. invoices : ใบแจ้งหนี้
--     (สร้างก่อน utility_readings เพราะ utility_readings อ้างถึง invoices)
-- ---------------------------------------------------------------------
create table public.invoices (
  invoice_id          int generated by default as identity primary key,
  invoice_no          varchar(50) not null unique,
  contract_id         int not null references public.contracts (contract_id) on delete restrict,
  billing_period      varchar(20) not null
                      check (billing_period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  rent_amount         decimal(10,2) not null default 0 check (rent_amount >= 0),
  water_amount        decimal(10,2) not null default 0 check (water_amount >= 0),
  electricity_amount  decimal(10,2) not null default 0 check (electricity_amount >= 0),
  fee_amount          decimal(10,2) not null default 0 check (fee_amount >= 0),
  total_amount        decimal(10,2) generated always as
                      (rent_amount + water_amount + electricity_amount + fee_amount) stored,
  due_date            date not null,
  status              varchar(30) not null default 'unpaid'
                      check (status in ('unpaid', 'paid', 'cancelled')),
  created_by          uuid references public.users (user_id) on delete set null,
  created_at          timestamptz not null default now()
);

-- สัญญาหนึ่งมีใบแจ้งหนี้ (ที่ไม่ถูกยกเลิก) ได้รอบบิลละ 1 ใบ
