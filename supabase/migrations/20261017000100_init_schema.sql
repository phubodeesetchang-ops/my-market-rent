-- 6. contracts : สัญญาเช่า (รวมคำขอเช่า status = pending)
-- ---------------------------------------------------------------------
create table public.contracts (
  contract_id      int generated by default as identity primary key,
  contract_no      varchar(50) not null unique,
  tenant_id        int not null references public.tenants (tenant_id) on delete restrict,
  stall_id         int not null references public.stalls (stall_id) on delete restrict,
  start_date       date not null,
  end_date         date not null,
  rent_amount      decimal(10,2) not null check (rent_amount >= 0),
  rent_period      varchar(20) not null
                   check (rent_period in ('monthly', 'yearly')),
  deposit_amount   decimal(10,2) check (deposit_amount >= 0),
  status           varchar(30) not null default 'pending'
                   check (status in ('pending', 'active', 'expired', 'cancelled', 'rejected')),
  renewed_from_id  int unique references public.contracts (contract_id) on delete set null,
  created_by       uuid references public.users (user_id) on delete set null,
  created_at       timestamptz not null default now(),

  constraint contracts_date_order check (end_date > start_date),
  -- แผงเดียวกันห้ามมีสัญญา active ที่ช่วงวันที่ทับกัน
  constraint contracts_no_overlap exclude using gist (
    stall_id with =,
    daterange(start_date, end_date, '[]') with &&
  ) where (status = 'active')
);

create index contracts_tenant_idx on public.contracts (tenant_id);
create index contracts_stall_idx  on public.contracts (stall_id);
create index contracts_status_idx on public.contracts (status);

