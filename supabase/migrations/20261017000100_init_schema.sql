-- 12. receipts : ใบเสร็จรับเงิน (1 การชำระที่ผ่าน = 1 ใบเสร็จ)
-- ---------------------------------------------------------------------
create table public.receipts (
  receipt_id    int generated by default as identity primary key,
  receipt_no    varchar(50) not null unique,
  payment_id    int not null unique references public.payments (payment_id) on delete restrict,
  receipt_date  date not null default current_date,
  amount        decimal(10,2) not null check (amount > 0),
  issued_by     uuid references public.users (user_id) on delete set null,
  created_at    timestamptz not null default now()
);

