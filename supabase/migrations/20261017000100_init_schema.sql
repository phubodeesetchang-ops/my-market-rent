-- 9. utility_readings : การจดมิเตอร์น้ำ-ไฟ
-- ---------------------------------------------------------------------
create table public.utility_readings (
  reading_id        int generated by default as identity primary key,
  stall_id          int not null references public.stalls (stall_id) on delete restrict,
  utility_type      varchar(30) not null
                    check (utility_type in ('electricity', 'water')),
  billing_period    varchar(20) not null
                    check (billing_period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  previous_reading  decimal(10,2) not null check (previous_reading >= 0),
  current_reading   decimal(10,2) not null,
  unit_used         decimal(10,2) generated always as (current_reading - previous_reading) stored,
  rate_per_unit     decimal(10,2) not null check (rate_per_unit >= 0),
  reading_date      date not null default current_date,
  invoice_id        int references public.invoices (invoice_id) on delete set null,
  created_by        uuid references public.users (user_id) on delete set null,
  created_at        timestamptz not null default now(),

  constraint utility_readings_not_backwards check (current_reading >= previous_reading),
  -- แผงหนึ่ง จดมิเตอร์แต่ละประเภทได้รอบบิลละ 1 ครั้ง
  unique (stall_id, utility_type, billing_period)
